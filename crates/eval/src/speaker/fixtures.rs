//! Licence-clean fixture records and deterministic session synthesis
//! (VOICE_PROFILES_SPEC §17.2, VP-181/VP-182/VP-184).
//!
//! Two jobs live here, and they are separate on purpose:
//!
//! * **The register.** [`FixtureManifest`] is the licence gate. Only the three
//!   corpora VP-181 allows are representable as a [`FixtureCorpus`], so a
//!   VoxCeleb row is not "rejected at review" — it does not deserialize. On
//!   top of that, every free-text field is scanned for the names VP-182
//!   forbids, because a LibriSpeech-labelled row whose note says "mixed with
//!   VoxConverse" is exactly the contamination the rule is about.
//! * **The generator.** [`SessionPlan::synthesize`] lays N speakers out on a
//!   timeline from a fixed seed with controlled overlap, which yields exact
//!   ground truth ([`SyntheticSession::rttm`], [`SyntheticSession::reference_turns`])
//!   deterministically — the property VP-181(a) buys by building fixtures
//!   instead of annotating them.
//!
//! Nothing here reads or writes audio. The timeline is the ground truth; the
//! audio for a committed fixture is produced by the documented recipe in
//! `docs/benchmarks/speaker-match-eval.md` from corpora we may not vendor in
//! full, and the harness itself runs on embeddings (see
//! [`super::embeddings`]), so CI needs no media at all.

use std::collections::BTreeSet;
use std::fmt;
use std::fmt::Write as _;

use plaudon_ai_diarization::der::ReferenceTurn;
use plaudon_domain::media::Sha256Digest;
use serde::{Deserialize, Serialize};

/// Schema version of the fixture manifest this build reads and writes.
pub const FIXTURE_MANIFEST_SCHEMA_VERSION: u32 = 1;

/// Corpus names that may never enter the repository or CI (VP-182).
///
/// Matched case-insensitively against every free-text field of a manifest,
/// after removing `-` and `_`, so `Vox_Celeb` and `aishell4` are caught too.
pub const FORBIDDEN_CORPORA: &[&str] = &["voxceleb", "voxconverse", "aishell4"];

/// Corpora that are licence-clean but download-on-demand only (VP-182).
///
/// AMI and ICSI are CC-BY-4.0 and are the genuine target domain, but they are
/// gigabytes of real meetings: an accuracy gate a developer runs locally, never
/// a committed fixture and never a CI download.
pub const DOWNLOAD_ON_DEMAND_CORPORA: &[&str] = &["ami", "icsi"];

/// A corpus a committed fixture may be derived from (VP-181).
///
/// The enum *is* the allowlist. Adding a variant is a licence decision that
/// has to pass review, and the register rows below travel into every report.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FixtureCorpus {
    /// Multi-speaker audio synthesized from LibriSpeech `test-clean`.
    LibriSpeechTestCleanDerived,
    /// MUSAN noise, mixed into a LibriSpeech-derived session.
    Musan,
    /// Kokoro-82M text-to-speech: the zero-human-voices smoke tier.
    KokoroTts,
    /// Scripted vectors with no audio behind them at all: the CI tier.
    ScriptedSynthetic,
}

impl FixtureCorpus {
    /// SPDX-style licence identifier of the source material.
    #[must_use]
    pub const fn licence(self) -> &'static str {
        match self {
            Self::LibriSpeechTestCleanDerived | Self::Musan => "CC-BY-4.0",
            Self::KokoroTts => "Apache-2.0",
            Self::ScriptedSynthetic => "not applicable (no recorded material)",
        }
    }

    /// Attribution line required by that licence, verbatim for `NOTICE`.
    #[must_use]
    pub const fn attribution(self) -> &'static str {
        match self {
            Self::LibriSpeechTestCleanDerived => {
                "LibriSpeech (Panayotov et al., openslr.org/12), CC-BY-4.0, derived from \
                 public-domain LibriVox recordings; used as test material only"
            }
            Self::Musan => "MUSAN (Snyder et al., openslr.org/17), CC-BY-4.0",
            Self::KokoroTts => "Kokoro-82M text-to-speech (hexgrad/Kokoro-82M), Apache-2.0",
            Self::ScriptedSynthetic => {
                "generated by plaudon-eval from a fixed seed; no recorded material"
            }
        }
    }

    /// Whether the fixture contains a real human being's voice.
    ///
    /// The TTS and scripted tiers do not, which is why they are the tier a
    /// contributor may regenerate without thinking about §17.5 at all.
    #[must_use]
    pub const fn has_human_voices(self) -> bool {
        matches!(
            self,
            Self::LibriSpeechTestCleanDerived | Self::Musan | Self::KokoroTts
        )
    }

    /// Whether whole fixture bytes of this tier may be committed to the repo.
    ///
    /// Only the scripted tier may: it has no media. The audio tiers are
    /// regenerated by recipe from corpora the contributor downloads, so the
    /// repository carries their ground truth and checksums, not their samples.
    #[must_use]
    pub const fn media_may_be_committed(self) -> bool {
        matches!(self, Self::ScriptedSynthetic)
    }
}

impl fmt::Display for FixtureCorpus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let text = match self {
            Self::LibriSpeechTestCleanDerived => "librispeech-test-clean-derived",
            Self::Musan => "musan",
            Self::KokoroTts => "kokoro-tts",
            Self::ScriptedSynthetic => "scripted-synthetic",
        };
        f.write_str(text)
    }
}

/// One channel/acoustic condition a fixture is evaluated under (VP-184).
///
/// The conditions are declared here so a report can key per-condition error
/// bars by a stable token. The transforms they name are applied by the audio
/// recipe (`docs/benchmarks/speaker-match-eval.md`); this crate only ever sees
/// the resulting embeddings, or scripted stand-ins for them.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Condition {
    /// Unmodified fixture audio.
    Clean,
    /// MUSAN noise mixed at a fixed SNR.
    NoiseMusan,
    /// Re-encoded through low-bitrate Opus (`crates/audio/src/opus.rs`).
    OpusLowBitrate,
    /// 300–3400 Hz telephone band-pass.
    TelephoneBandpass,
    /// Convolved with a room impulse response.
    RoomImpulseResponse,
}

impl Condition {
    /// Every condition, in report order.
    pub const ALL: &'static [Self] = &[
        Self::Clean,
        Self::NoiseMusan,
        Self::OpusLowBitrate,
        Self::TelephoneBandpass,
        Self::RoomImpulseResponse,
    ];

    /// Stable token used in manifests, trial ids and reports.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Clean => "clean",
            Self::NoiseMusan => "noise_musan",
            Self::OpusLowBitrate => "opus_low_bitrate",
            Self::TelephoneBandpass => "telephone_bandpass",
            Self::RoomImpulseResponse => "room_impulse_response",
        }
    }

    /// Whether this condition leaves the signal path untouched.
    #[must_use]
    pub const fn is_reference_condition(self) -> bool {
        matches!(self, Self::Clean)
    }
}

impl fmt::Display for Condition {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Why a fixture manifest was refused.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, thiserror::Error)]
#[serde(tag = "reason", rename_all = "snake_case")]
pub enum FixtureRejection {
    /// A field named a corpus VP-182 forbids.
    #[error("fixture `{fixture_id}` names the forbidden corpus `{corpus}` in `{field}` (VP-182)")]
    ForbiddenCorpus {
        /// Offending fixture, or `manifest` for a library-level field.
        fixture_id: String,
        /// Which field carried the name.
        field: String,
        /// The forbidden corpus that was named.
        corpus: String,
    },

    /// A field named a corpus that is download-on-demand only.
    #[error(
        "fixture `{fixture_id}` names `{corpus}`, which is a developer-local accuracy gate, not a \
         committed fixture (VP-182)"
    )]
    DownloadOnDemandOnly {
        /// Offending fixture.
        fixture_id: String,
        /// The corpus that may not be committed.
        corpus: String,
    },

    /// The manifest declared a schema version this build does not read.
    #[error("fixture manifest schema version {found} is not {FIXTURE_MANIFEST_SCHEMA_VERSION}")]
    UnsupportedSchemaVersion {
        /// Version the file declared.
        found: u32,
    },

    /// Two rows claimed the same identifier.
    #[error("fixture id `{fixture_id}` appears more than once")]
    DuplicateId {
        /// The repeated identifier.
        fixture_id: String,
    },

    /// A row carried no speaker labels, so it can neither be a trial nor a
    /// diarization reference.
    #[error("fixture `{fixture_id}` declares no speakers")]
    NoSpeakers {
        /// Offending fixture.
        fixture_id: String,
    },

    /// A row carried human voices but no media digest, so what was measured
    /// cannot be identified later.
    #[error("fixture `{fixture_id}` has human voices but records no media sha256")]
    MissingMediaDigest {
        /// Offending fixture.
        fixture_id: String,
    },

    /// A row claimed its media is committed, but its tier forbids that.
    #[error("fixture `{fixture_id}` is `{corpus}`, whose media may not be committed (VP-181)")]
    MediaMayNotBeCommitted {
        /// Offending fixture.
        fixture_id: String,
        /// Tier that forbids committing media.
        corpus: FixtureCorpus,
    },
}

/// Why a manifest could not be read at all.
#[derive(Debug, thiserror::Error)]
pub enum FixtureError {
    /// The document is not valid JSON, or names a corpus outside the
    /// VP-181 allowlist (an unknown `corpus` value fails here).
    #[error("fixture manifest is not readable: {0}")]
    Malformed(#[from] serde_json::Error),

    /// The document parsed but broke the licence or completeness rules.
    #[error("fixture manifest was refused: {}", render(.0))]
    Refused(Vec<FixtureRejection>),
}

fn render(rejections: &[FixtureRejection]) -> String {
    rejections
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join("; ")
}

/// One fixture row: what it is, where it came from, and under which licence.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FixtureRecord {
    /// Stable identifier, used in trial ids.
    pub fixture_id: String,
    /// Corpus the material derives from (the VP-181 allowlist).
    pub corpus: FixtureCorpus,
    /// Channel condition this row represents.
    pub condition: Condition,
    /// Speaker labels present in the fixture.
    pub speakers: Vec<String>,
    /// Nominal length in milliseconds.
    pub duration_ms: u64,
    /// Digest of the media, when media exists.
    pub media_sha256: Option<Sha256Digest>,
    /// Whether the media bytes live in the repository.
    pub media_committed: bool,
    /// How the fixture is produced, in one sentence. Scanned for VP-182 names.
    pub recipe: String,
}

impl FixtureRecord {
    /// Attribution row this fixture obliges us to publish.
    #[must_use]
    pub fn attribution(&self) -> AttributionRow {
        AttributionRow {
            corpus: self.corpus,
            licence: self.corpus.licence().to_owned(),
            attribution: self.corpus.attribution().to_owned(),
        }
    }
}

/// An attribution obligation, carried into every report (VP-181).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct AttributionRow {
    /// Corpus the obligation comes from.
    pub corpus: FixtureCorpus,
    /// Licence identifier.
    pub licence: String,
    /// Attribution text.
    pub attribution: String,
}

/// The fixture library: a licence-checked set of rows.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FixtureManifest {
    /// Must equal [`FIXTURE_MANIFEST_SCHEMA_VERSION`].
    pub schema_version: u32,
    /// Identifier of this library, published in the report.
    pub library_id: String,
    /// Free-text provenance note. Scanned for VP-182 names.
    pub notes: String,
    /// The rows.
    pub fixtures: Vec<FixtureRecord>,
}

impl FixtureManifest {
    /// Parse and licence-check a manifest document.
    pub fn parse(document: &str) -> Result<Self, FixtureError> {
        let manifest: Self = serde_json::from_str(document)?;
        let rejections = manifest.rejections();
        if rejections.is_empty() {
            Ok(manifest)
        } else {
            Err(FixtureError::Refused(rejections))
        }
    }

    /// Every rule this manifest breaks, in declaration order.
    ///
    /// Returned as a list rather than a first error so a contributor fixing a
    /// fixture set sees all of it at once.
    #[must_use]
    pub fn rejections(&self) -> Vec<FixtureRejection> {
        let mut rejections = Vec::new();
        if self.schema_version != FIXTURE_MANIFEST_SCHEMA_VERSION {
            rejections.push(FixtureRejection::UnsupportedSchemaVersion {
                found: self.schema_version,
            });
        }
        scan_text("manifest", "notes", &self.notes, &mut rejections);
        scan_text("manifest", "library_id", &self.library_id, &mut rejections);

        let mut seen = BTreeSet::new();
        for fixture in &self.fixtures {
            if !seen.insert(fixture.fixture_id.as_str()) {
                rejections.push(FixtureRejection::DuplicateId {
                    fixture_id: fixture.fixture_id.clone(),
                });
            }
            scan_text(
                &fixture.fixture_id,
                "recipe",
                &fixture.recipe,
                &mut rejections,
            );
            scan_text(
                &fixture.fixture_id,
                "fixture_id",
                &fixture.fixture_id,
                &mut rejections,
            );
            for speaker in &fixture.speakers {
                scan_text(&fixture.fixture_id, "speakers", speaker, &mut rejections);
            }
            if fixture.speakers.is_empty() {
                rejections.push(FixtureRejection::NoSpeakers {
                    fixture_id: fixture.fixture_id.clone(),
                });
            }
            if fixture.corpus.has_human_voices() && fixture.media_sha256.is_none() {
                rejections.push(FixtureRejection::MissingMediaDigest {
                    fixture_id: fixture.fixture_id.clone(),
                });
            }
            if fixture.media_committed && !fixture.corpus.media_may_be_committed() {
                rejections.push(FixtureRejection::MediaMayNotBeCommitted {
                    fixture_id: fixture.fixture_id.clone(),
                    corpus: fixture.corpus,
                });
            }
        }
        rejections
    }

    /// Distinct attribution obligations of this library.
    #[must_use]
    pub fn attributions(&self) -> Vec<AttributionRow> {
        let mut rows: Vec<AttributionRow> = self
            .fixtures
            .iter()
            .map(FixtureRecord::attribution)
            .collect();
        rows.sort();
        rows.dedup();
        rows
    }

    /// Distinct speaker labels across the library.
    #[must_use]
    pub fn speakers(&self) -> BTreeSet<&str> {
        self.fixtures
            .iter()
            .flat_map(|fixture| fixture.speakers.iter().map(String::as_str))
            .collect()
    }

    /// Content digest of the manifest, so a report names the exact library.
    #[must_use]
    pub fn digest(&self) -> Sha256Digest {
        let canonical = serde_json::to_vec(self).expect("a fixture manifest always serializes");
        Sha256Digest::of(&canonical)
    }
}

/// Fold a field down to the form the forbidden-name scan compares.
fn fold(text: &str) -> String {
    text.chars()
        .filter(char::is_ascii_alphanumeric)
        .map(|c| c.to_ascii_lowercase())
        .collect()
}

fn scan_text(fixture_id: &str, field: &str, text: &str, out: &mut Vec<FixtureRejection>) {
    let folded = fold(text);
    for forbidden in FORBIDDEN_CORPORA {
        if folded.contains(forbidden) {
            out.push(FixtureRejection::ForbiddenCorpus {
                fixture_id: fixture_id.to_owned(),
                field: field.to_owned(),
                corpus: (*forbidden).to_owned(),
            });
        }
    }
    for on_demand in DOWNLOAD_ON_DEMAND_CORPORA {
        // Word match, so `ami` fires on "AMI meetings" but not on "ceramic".
        if text
            .split(|c: char| !c.is_ascii_alphanumeric())
            .any(|word| word.eq_ignore_ascii_case(on_demand))
        {
            out.push(FixtureRejection::DownloadOnDemandOnly {
                fixture_id: fixture_id.to_owned(),
                corpus: (*on_demand).to_owned(),
            });
        }
    }
}

/// How a synthetic multi-speaker session is laid out (VP-181(a)).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SessionPlan {
    /// Identifier of the session, used in the RTTM file column.
    pub session_id: String,
    /// Speakers in turn order.
    pub speakers: Vec<String>,
    /// Utterances each speaker contributes.
    pub utterances_per_speaker: u32,
    /// Length of one utterance.
    pub utterance_ms: u64,
    /// Silence between consecutive non-overlapping turns.
    pub gap_ms: u64,
    /// Every `overlap_every`-th turn starts before its predecessor ends.
    /// Zero disables overlap.
    pub overlap_every: u32,
    /// How long such an overlap lasts (the cross-fade region).
    pub overlap_ms: u64,
    /// Seed for the turn-order permutation.
    pub seed: u64,
}

impl SessionPlan {
    /// Lay the speakers out on a timeline deterministically.
    ///
    /// The order is a seeded permutation of `speakers.len() * utterances_per_speaker`
    /// turns; the timing is arithmetic. The same plan therefore always yields
    /// the same RTTM, which is what makes the ground truth exact instead of
    /// annotated.
    #[must_use]
    pub fn synthesize(&self) -> SyntheticSession {
        let mut order: Vec<usize> = (0..self.speakers.len())
            .flat_map(|speaker| std::iter::repeat_n(speaker, self.utterances_per_speaker as usize))
            .collect();
        // Fisher-Yates with a seeded counter PRNG: no dependency, and the
        // permutation is reproducible across platforms and Rust versions.
        let mut state = self.seed ^ 0x9E37_79B9_7F4A_7C15;
        for index in (1..order.len()).rev() {
            state = super::next_u64(state);
            let pick = (state % (index as u64 + 1)) as usize;
            order.swap(index, pick);
        }

        let mut turns = Vec::with_capacity(order.len());
        let mut counters = vec![0u32; self.speakers.len()];
        let mut cursor = 0u64;
        for (position, speaker_index) in order.into_iter().enumerate() {
            let overlaps = self.overlap_every > 0
                && position > 0
                && (position as u32).is_multiple_of(self.overlap_every)
                && self.overlap_ms > 0;
            let start_ms = if overlaps {
                cursor.saturating_sub(self.overlap_ms)
            } else {
                cursor + if position == 0 { 0 } else { self.gap_ms }
            };
            let end_ms = start_ms + self.utterance_ms;
            let utterance = counters[speaker_index];
            counters[speaker_index] += 1;
            turns.push(SessionTurn {
                speaker: self.speakers[speaker_index].clone(),
                utterance,
                start_ms,
                end_ms,
                overlaps_previous: overlaps,
            });
            cursor = end_ms;
        }

        SyntheticSession {
            session_id: self.session_id.clone(),
            turns,
        }
    }
}

/// One laid-out turn of a synthetic session.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SessionTurn {
    /// Speaker label.
    pub speaker: String,
    /// Which utterance of that speaker this is (0-based).
    pub utterance: u32,
    /// Inclusive start in milliseconds.
    pub start_ms: u64,
    /// Exclusive end in milliseconds.
    pub end_ms: u64,
    /// Whether this turn starts before its predecessor ended.
    pub overlaps_previous: bool,
}

/// A laid-out session and its exact ground truth.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SyntheticSession {
    /// Identifier, used as the RTTM file column.
    pub session_id: String,
    /// Turns in timeline order.
    pub turns: Vec<SessionTurn>,
}

impl SyntheticSession {
    /// Ground truth in the form `crates/ai-diarization` scores against.
    #[must_use]
    pub fn reference_turns(&self) -> Vec<ReferenceTurn> {
        self.turns
            .iter()
            .map(|turn| ReferenceTurn::new(turn.speaker.clone(), turn.start_ms, turn.end_ms))
            .collect()
    }

    /// Ground truth as NIST RTTM, the interchange format of the field.
    #[must_use]
    pub fn rttm(&self) -> String {
        let mut out = String::new();
        for turn in &self.turns {
            let start = turn.start_ms as f64 / 1000.0;
            let duration = (turn.end_ms - turn.start_ms) as f64 / 1000.0;
            writeln!(
                out,
                "SPEAKER {} 1 {start:.3} {duration:.3} <NA> <NA> {} <NA> <NA>",
                self.session_id, turn.speaker
            )
            .expect("formatting into a String cannot fail");
        }
        out
    }

    /// Total speech, counting overlapped speech once per simultaneous speaker.
    #[must_use]
    pub fn speech_ms(&self) -> u64 {
        self.turns
            .iter()
            .map(|turn| turn.end_ms - turn.start_ms)
            .sum()
    }

    /// Milliseconds during which two speakers are active at once.
    #[must_use]
    pub fn overlap_ms(&self) -> u64 {
        self.turns
            .windows(2)
            .map(|pair| pair[0].end_ms.saturating_sub(pair[1].start_ms))
            .sum()
    }

    /// Last millisecond of the session.
    #[must_use]
    pub fn end_ms(&self) -> u64 {
        self.turns.iter().map(|turn| turn.end_ms).max().unwrap_or(0)
    }
}
