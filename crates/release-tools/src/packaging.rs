    /// The worked example committed under `packaging/examples/` is what the
    /// templates render today, for a release that does not exist: version
    /// 0.0.0, two fixture files, an URL that resolves to nothing. It is there
    /// so a reader can see the shape of the output without a release, and it
    /// is compared byte for byte so the templates cannot drift away from it
    /// unnoticed.
    ///
    /// Regenerate with
    /// `PLAUDON_UPDATE_PACKAGING_EXAMPLES=1 cargo test -p plaudon-release-tools packaging`.
    #[test]
    fn the_committed_example_is_what_the_templates_render() {
        let dir = tempfile::tempdir().expect("tempdir");
        let zip = dir.path().join("Plaudon.app.zip");
        let msi = dir.path().join("Plaudon-0.0.0-x64.msi");
        std::fs::write(&zip, b"packaging example: not a bundle\n").expect("write zip");
        std::fs::write(&msi, b"packaging example: not an installer\n").expect("write msi");
        let release = Release::from_files(
            "0.0.0",
            DEFAULT_REPOSITORY,
            &zip,
            &msi,
            "13.0",
            "2026-01-01",
        )
        .expect("example release");
        let rendered = render(&templates(), &release).expect("render");

        let examples = repo_root().join("packaging/examples");
        let update = std::env::var_os("PLAUDON_UPDATE_PACKAGING_EXAMPLES").is_some();
        if update {
            std::fs::create_dir_all(&examples).expect("examples directory");
        }
        for (name, contents) in rendered.files() {
            let path = examples.join(name);
            if update {
                std::fs::write(&path, contents).expect("write example");
                continue;
            }
            let committed = std::fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
            assert_eq!(
                committed, contents,
                "packaging/examples/{name} is stale; regenerate it with \
                 PLAUDON_UPDATE_PACKAGING_EXAMPLES=1"
            );
        }
    }
